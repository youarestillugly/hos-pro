/* =====================================
   OPEN PROFILE
===================================== */

function openProfile(index) {

    const member = members[index];

    document.getElementById("profileImage").src =
        member.image;

    document.getElementById("profileImage").alt =
        member.name;

    document.getElementById("profileName").textContent =
        member.name;

    document.getElementById("profileCourse").textContent =
        member.Year_course;

    document.getElementById("profilePosition").textContent =
        member.position;


    const facts =
        document.getElementById("profileFacts");

    facts.innerHTML = "<ol></ol>";

    const list =
        facts.querySelector("ol");


    member.facts.forEach(function(fact) {

        const li =
            document.createElement("li");

        li.textContent = fact;

        list.appendChild(li);

    });


    document
        .getElementById("profileModal")
        .classList.add("active");


    document.body.style.overflow = "hidden";

}



/* =====================================
   CLOSE PROFILE
===================================== */

function closeProfile() {

    document
        .getElementById("profileModal")
        .classList.remove("active");

    document.body.style.overflow = "auto";

}



/* =====================================
   CLOSE WHEN CLICKING OUTSIDE
===================================== */

document
    .getElementById("profileModal")
    .addEventListener("click", function(event) {

        if (
            event.target === this
        ) {

            closeProfile();

        }

    });



/* =====================================
   ESCAPE KEY
===================================== */

document.addEventListener("keydown", function(event) {

    if (event.key === "Escape") {

        closeProfile();

    }

});